function build(src: string): Set<string> {
  return new Set(
    src
      .split(/\s+/)
      .filter(Boolean)
      .map((w) => compareKey(w.replace(/_/g, " ")))
  );
}

export const DICTIONARY: Set<string>[] = [build(HUMAN), build(ANIMAL), build(PLANT), build(OBJECT), build(COUNTRY)];

/** هل الكلمة معروفة في قاموس التصنيف؟ نجرب أيضاً حذف علامات الجمع والتأنيث الشائعة */
export function inDictionary(cat: number, answer: string): boolean {
  const set = DICTIONARY[cat];
  const k = compareKey(answer);
  if (set.has(k)) return true;
  // أشكال شائعة: الجمع والتأنيث (قطط/قطه، بقرات، عصافير...)
  const variants = [k.replace(/(ات|ين|ون|ه)$/, ""), k + "ه", k.replace(/^ابو/, "ابو")];
  if (cat === 0 && k.startsWith("عبد") && k.length >= 6) return true; // أسماء مركبة تبدأ بعبد
  return variants.some((v) => v.length >= 2 && set.has(v));
}
